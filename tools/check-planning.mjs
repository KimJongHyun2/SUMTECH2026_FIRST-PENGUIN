import fs from 'node:fs';
import assert from 'node:assert/strict';
import yaml from 'js-yaml';
const load=p=>yaml.load(fs.readFileSync(p,'utf8'));
const p=load('docs/problem.yaml'), s=load('docs/scenarios.yaml'), policy=load('docs/planning-policy.yaml');
const filled=v=>{if(v===null||v===undefined||v==='')throw Error('빈 값');if(Array.isArray(v)){assert(v.length);v.forEach(filled);}else if(typeof v==='object')Object.values(v).forEach(filled);};
filled(p);filled(s);filled(policy);
assert.equal(new Set(p.features.map(f=>f.id)).size,p.features.length);
assert.equal(s.scenarios.length,8);
s.scenarios.forEach((x,i)=>{assert.equal(x.id,`S${i+1}`);assert(x.steps.length>0&&x.steps.length<=12);assert(x.expected);});
assert(!p.features.some(f=>f.id==='F11'));
const prd=fs.readFileSync('docs/prd.md','utf8');
for(const f of p.features)assert(prd.includes(f.id));
const cases=JSON.parse(fs.readFileSync('docs/references/2026-10-30/report-calculation.source.json','utf8')).cases;
const length=xs=>{const a=xs.map(x=>[...x]).sort((a,b)=>a[0]-b[0]);let n=0,end=-Infinity;for(const [l,r]of a){n+=Math.max(0,r-Math.max(l,end));end=Math.max(end,r);}return n;};
const valid=[[0,40],[50,90]];
const intersect=xs=>xs.flatMap(([a,b])=>valid.map(([c,d])=>[Math.max(a,c),Math.min(b,d)]).filter(([l,r])=>r>l));
const result=xs=>{const v=length(valid),d=length(intersect(xs));return {valid_seconds:v,deviation_seconds:d,deviation_percent:d/v*100};};
const split=(onset,end)=>({first_seconds:Math.max(0,Math.min(end,1800)-onset),next_seconds:Math.max(0,end-Math.max(onset,1800)),first_new_events:onset<1800?1:0,next_new_events:onset>=1800?1:0});
const actual=[result([[10,30],[20,40]]),result([[25,65]]),split(1790,1810),split(1795,1810),{valid_seconds:0,deviation_seconds:0,deviation_percent:null},{complete_windows:Math.floor(1800/policy.reportValidSeconds),partial_windows:1800%policy.reportValidSeconds?1:0}];
cases.forEach((c,i)=>assert.deepEqual(actual[i],c.expected,c.id));
assert.equal(JSON.parse(fs.readFileSync('docs/references/2026-10-30/report-calculation.source.json','utf8')).app_e2e_executed,false);
console.log(`문서 검사 통과: ${p.features.length} 기능, 8 흐름, 빈 값 없음, C01~C06 독립 산술 일치. 앱/E2E 미실행.`);
